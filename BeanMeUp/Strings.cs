/// <summary>Schriften passend zur Sprache: Segoe UI, für Japanisch/Chinesisch/Koreanisch die Windows-Systemschriften.</summary>
static class UiFonts
{
    static string Family => L.Code switch
    {
        "ja" => "Yu Gothic UI",
        "zh" => "Microsoft YaHei UI",
        "ko" => "Malgun Gothic",
        _ => "Segoe UI",
    };

    public static Font Create(float pixels, bool semibold = false)
    {
        if (semibold)
        {
            // Segoe UI und Yu Gothic UI haben eine eigene Semibold-Familie, sonst Fettdruck
            string semiFamily = Family + " Semibold";
            if (Family is "Segoe UI" or "Yu Gothic UI" && Installed(semiFamily))
                return new Font(semiFamily, pixels, GraphicsUnit.Pixel);
            return new Font(Family, pixels, FontStyle.Bold, GraphicsUnit.Pixel);
        }
        return new Font(Family, pixels, GraphicsUnit.Pixel);
    }

    static bool Installed(string family)
    {
        try
        {
            using var f = new FontFamily(family);
            return true;
        }
        catch (ArgumentException)
        {
            return false;
        }
    }
}
