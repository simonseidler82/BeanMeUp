    ];

    static readonly Dictionary<string, Dictionary<string, string>> Tables = new()
    {
        // Basis-Texte + Ergänzungen aus StringsUpdates.cs (spätere Einträge überschreiben frühere)
        ["de"] = Parse(De + "\n" + De2), ["en"] = Parse(En + "\n" + En2), ["fr"] = Parse(Fr + "\n" + Fr2), ["es"] = Parse(Es + "\n" + Es2),
        ["it"] = Parse(It + "\n" + It2), ["pt"] = Parse(Pt + "\n" + Pt2), ["nl"] = Parse(Nl + "\n" + Nl2), ["pl"] = Parse(Pl + "\n" + Pl2),
        ["cs"] = Parse(Cs + "\n" + Cs2), ["sv"] = Parse(Sv + "\n" + Sv2), ["tr"] = Parse(Tr + "\n" + Tr2), ["ru"] = Parse(Ru + "\n" + Ru2),
        ["uk"] = Parse(Uk + "\n" + Uk2), ["ja"] = Parse(Ja + "\n" + Ja2), ["zh"] = Parse(Zh + "\n" + Zh2), ["ko"] = Parse(Ko + "\n" + Ko2),
    };

    /// <summary>Aktive Sprache (zweistelliger Code).</summary>
    public static string Code { get; private set; } = "en";

    /// <summary>Sprache festlegen: "auto"/leer = Windows-Anzeigesprache, sonst Code wie "fr".</summary>
    public static void Init(string? setting)
    {
        string code = string.IsNullOrWhiteSpace(setting) || setting!.Trim().Equals("auto", StringComparison.OrdinalIgnoreCase)
            ? SystemLanguage()
            : setting.Trim().ToLowerInvariant();
        Code = Tables.ContainsKey(code) ? code : "en";
    }

    /// <summary>Windows-Anzeigesprache, falls übersetzt – sonst Englisch.</summary>
    public static string SystemLanguage()
    {
        string two = CultureInfo.CurrentUICulture.TwoLetterISOLanguageName.ToLowerInvariant();
        return Tables.ContainsKey(two) ? two : "en";
    }

    public static string T(string key)
    {
        if (Tables[Code].TryGetValue(key, out var text)) return text;
        if (Tables["en"].TryGetValue(key, out var english)) return english;
        return key;
    }

    public static string T(string key, params object[] args) => string.Format(T(key), args);

    /// <summary>Dezente Fußzeile: Kürzel und Versionsnummer, z. B. "SiS · v2.2.2".</summary>
    public static string Credits => $"SiS · v{typeof(L).Assembly.GetName().Version?.ToString(3)}";

    static Dictionary<string, string> Parse(string table)
    {
        var result = new Dictionary<string, string>();
        foreach (var raw in table.Split('\n'))
        {
            string line = raw.TrimEnd('\r');
            int eq = line.IndexOf('=');
            if (eq <= 0) continue;
            result[line.Substring(0, eq).Trim()] = line.Substring(eq + 1).Replace("\\n", "\n");
        }
        return result;
    }

